"""Regenerate the annotated evidence frames quoted in docs/REPORT.md §5.

The four frames in evidence/ are the only images the report and the demo video point
at, so they must be reproducible from the code that ships. This script re-runs the
agent loop on each seed and draws:

  yellow  ground truth from the scene generator
  red     the merged multi-view prediction the loop returned

Writes
  evidence/scene_<seed>.png         annotated accepting view (canonical panel)
  evidence/scene_<seed>_input.png   the first raw capture the loop had to work with
  docs/video_src/scene_traces.txt   the step trace as plain text (used by the video)

Run: .venv/bin/python src/make_evidence.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

import cv2

from agent import run_agent
from perception import perceive
from scene_sim import PANEL_H, make_scene, render_canonical

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "evidence"
TRACE_DIR = ROOT / "docs" / "video_src"

SEEDS = (2000, 2002, 2005, 2011)

YELLOW = (0, 230, 255)
RED = (60, 60, 235)


def _header(img, text: str) -> None:
    cv2.rectangle(img, (0, 0), (img.shape[1], 30), (0, 0, 0), -1)
    cv2.putText(img, text, (10, 21), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 1, cv2.LINE_AA)


def main() -> None:
    ref = render_canonical(reference=True)
    EVIDENCE.mkdir(exist_ok=True)
    TRACE_DIR.mkdir(parents=True, exist_ok=True)
    trace_lines = ["# per-scene decision traces, regenerated by src/make_evidence.py", ""]

    for seed in SEEDS:
        scene = make_scene(seed=seed, hard=True)
        cam = scene.cam
        first = scene.capture()
        inp = first.copy()
        _header(inp, f"scene {seed} input | exposure {cam.exposure:.2f} blur_sigma {cam.blur_sigma:.2f} "
                     f"noise {cam.noise_sigma:.1f} jpeg {cam.jpeg_quality} yaw {cam.yaw:+.1f}")
        cv2.imwrite(str(EVIDENCE / f"scene_{seed}_input.png"), inp)

        report = run_agent(scene, ref)
        final = perceive(scene.capture(), ref)
        base = final.registered_bgr if final.registered_bgr is not None else first.copy()

        img = base.copy()
        for g in scene.defects:
            x, y, w, h = [int(v) for v in g["bbox"]]
            cv2.rectangle(img, (x, y), (x + w, y + h), YELLOW, 2)
            cv2.putText(img, f"GT {g['type']}", (x, max(16, y - 6)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.45, YELLOW, 1, cv2.LINE_AA)
        for d in report.defects:
            x, y, w, h = [int(v) for v in d.bbox]
            cv2.rectangle(img, (x - 5, y - 5), (x + w + 5, y + h + 5), RED, 2)
            cv2.putText(img, f"{d.type} {d.confidence:.2f}", (x - 5, max(16, y - 20)),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.45, RED, 1, cv2.LINE_AA)

        actions = " -> ".join(s.action for s in report.steps)
        _header(img, f"scene {seed} | GT {len(scene.defects)} (yellow) | merged {len(report.defects)} (red) "
                     f"| steps {len(report.steps)}: {actions}")
        cv2.imwrite(str(EVIDENCE / f"scene_{seed}.png"), img)

        trace_lines.append(f"scene {seed}  camera: exposure {cam.exposure:.2f} blur {cam.blur_sigma:.2f} "
                           f"noise {cam.noise_sigma:.1f} jpeg {cam.jpeg_quality}")
        trace_lines.append(f"  ground truth ({len(scene.defects)}): " +
                           ", ".join(g["type"] for g in scene.defects))
        for s in report.steps:
            trace_lines.append(
                f"  step {s.n}  {s.action:<15} luma {s.brightness:6.1f}  sharp {s.sharpness:6.1f}  "
                f"markers {s.markers}  | {s.reason}")
            found = ", ".join(f"{d['type']} {d['confidence']:.2f}" for d in s.defects) or "none"
            trace_lines.append(f"          found: {found}")
        trace_lines.append(f"  merged verdict ({len(report.defects)}): " +
                           ", ".join(f"{d.type} {d.confidence:.2f}" for d in report.defects))
        trace_lines.append("")

        print(f"scene {seed}: GT {len(scene.defects)}, merged {len(report.defects)}, "
              f"steps {len(report.steps)} [{actions}]")

    (TRACE_DIR / "scene_traces.txt").write_text("\n".join(trace_lines), encoding="utf-8")
    print("wrote", EVIDENCE, "and", TRACE_DIR / "scene_traces.txt")


if __name__ == "__main__":
    main()
